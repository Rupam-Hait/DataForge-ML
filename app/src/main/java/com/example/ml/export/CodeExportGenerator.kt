    fun generateTensorFlow(dataset: Dataset, hyperparams: Hyperparameters): String {
        val numFeatures = if (dataset.numericFeatures.isNotEmpty()) dataset.numericFeatures[0].size else dataset.featuresCount
        val isClassification = dataset.taskType != TaskType.REGRESSION
        val numClasses = if (isClassification) kotlin.math.max(2, dataset.classLabels.size) else 1
        val finalActivation = if (isClassification) (if (numClasses > 2) "'softmax'" else "'sigmoid'") else "'linear'"
        val lossVal = if (isClassification) (if (numClasses > 2) "'sparse_categorical_crossentropy'" else "'binary_crossentropy'") else "'mse'"

        val sb = StringBuilder()
        sb.appendLine("# ==============================================================================")
        sb.appendLine("# Model Training Script (TensorFlow 2.x / Keras)")
        sb.appendLine("# Dataset: ${dataset.title} (${dataset.category.displayName})")
        sb.appendLine("# Generated by DataForge ML")
        sb.appendLine("# ==============================================================================")
        sb.appendLine()
        sb.appendLine("import tensorflow as tf")
        sb.appendLine("from tensorflow import keras")
        sb.appendLine("from tensorflow.keras import layers")
        sb.appendLine("from sklearn.model_selection import train_test_split")
        sb.appendLine("from sklearn.preprocessing import StandardScaler")
        sb.appendLine("import numpy as np")
        sb.appendLine()
        sb.appendLine("X = np.array(${dataset.numericFeatures.take(25)}, dtype=np.float32)")
        sb.appendLine("y = np.array(${dataset.numericTargets.take(25)}, dtype=np.float32)")
        sb.appendLine()
        sb.appendLine("X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=${hyperparams.testSplitRatio}, random_state=42)")
        sb.appendLine("scaler = StandardScaler()")
        sb.appendLine("X_train = scaler.fit_transform(X_train)")
        sb.appendLine("X_test = scaler.transform(X_test)")
        sb.appendLine()
        sb.appendLine("model = keras.Sequential([")
        sb.appendLine("    layers.Input(shape=($numFeatures,)),")
        sb.appendLine("    layers.Dense(${hyperparams.hiddenUnits}, activation='relu'),")
        sb.appendLine("    layers.BatchNormalization(),")
        sb.appendLine("    layers.Dropout(${hyperparams.dropoutRate}),")
        sb.appendLine("    layers.Dense(max(8, ${hyperparams.hiddenUnits} // 2), activation='relu'),")
        sb.appendLine("    layers.Dense($numClasses, activation=$finalActivation)")
        sb.appendLine("])")
        sb.appendLine()
        sb.appendLine("model.compile(")
        sb.appendLine("    optimizer=keras.optimizers.Adam(learning_rate=${hyperparams.learningRate}),")
        sb.appendLine("    loss=$lossVal,")
        sb.appendLine("    metrics=${if (isClassification) "['accuracy']" else "['mae']"}")
        sb.appendLine(")")
        sb.appendLine()
        sb.appendLine("model.summary()")
        sb.appendLine()
        sb.appendLine("history = model.fit(")
        sb.appendLine("    X_train, y_train,")
        sb.appendLine("    validation_data=(X_test, y_test),")
        sb.appendLine("    epochs=${hyperparams.epochs},")
        sb.appendLine("    batch_size=${hyperparams.batchSize},")
        sb.appendLine("    verbose=1")
        sb.appendLine(")")
        sb.appendLine()
        sb.appendLine("# Export to TensorFlow Lite")
        sb.appendLine("converter = tf.lite.TFLiteConverter.from_keras_model(model)")
        sb.appendLine("converter.optimizations = [tf.lite.Optimize.DEFAULT]")
        sb.appendLine("tflite_model = converter.convert()")
        sb.appendLine("with open('dataforge_model.tflite', 'wb') as f:")
        sb.appendLine("    f.write(tflite_model)")
        sb.appendLine("print('Model exported as dataforge_model.tflite!')")
        return sb.toString()
    }

    fun generateScikitLearn(dataset: Dataset, hyperparams: Hyperparameters): String {
        val isClassification = dataset.taskType != TaskType.REGRESSION

        val sb = StringBuilder()
        sb.appendLine("# ==============================================================================")
        sb.appendLine("# Model Training Script (Scikit-Learn / Joblib)")
        sb.appendLine("# Dataset: ${dataset.title}")
        sb.appendLine("# Generated by DataForge ML")
        sb.appendLine("# ==============================================================================")
        sb.appendLine()
        sb.appendLine("import numpy as np")
        sb.appendLine("from sklearn.model_selection import train_test_split")
        sb.appendLine("from sklearn.preprocessing import StandardScaler")
        sb.appendLine("from sklearn.pipeline import Pipeline")
        sb.appendLine("import joblib")
        sb.appendLine()
        sb.appendLine("X = np.array(${dataset.numericFeatures.take(25)})")
        sb.appendLine("y = np.array(${dataset.numericTargets.take(25)})")
        sb.appendLine()
        sb.appendLine("X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=${hyperparams.testSplitRatio}, random_state=42)")
        sb.appendLine()

        if (isClassification) {
            sb.appendLine("from sklearn.ensemble import RandomForestClassifier")
            sb.appendLine("from sklearn.metrics import classification_report")
            sb.appendLine()
            sb.appendLine("model = RandomForestClassifier(n_estimators=100, max_depth=${hyperparams.maxTreeDepth}, random_state=42)")
            sb.appendLine("pipeline = Pipeline([('scaler', StandardScaler()), ('clf', model)])")
            sb.appendLine("pipeline.fit(X_train, y_train)")
            sb.appendLine("y_pred = pipeline.predict(X_test)")
            sb.appendLine("print(classification_report(y_test, y_pred))")
        } else {
            sb.appendLine("from sklearn.linear_model import Ridge")
            sb.appendLine("from sklearn.metrics import mean_squared_error, r2_score")
            sb.appendLine()
            sb.appendLine("model = Ridge(alpha=1.0)")
            sb.appendLine("pipeline = Pipeline([('scaler', StandardScaler()), ('reg', model)])")
            sb.appendLine("pipeline.fit(X_train, y_train)")
            sb.appendLine("y_pred = pipeline.predict(X_test)")
            sb.appendLine("print('R2 Fit:', r2_score(y_test, y_pred))")
            sb.appendLine("print('MSE:', mean_squared_error(y_test, y_pred))")
        }

        sb.appendLine()
        sb.appendLine("joblib.dump(pipeline, 'dataforge_${dataset.id}.pkl')")
        sb.appendLine("print('Saved pipeline artifact!')")
        return sb.toString()
    }

    fun generateCsv(dataset: Dataset): String {
        if (dataset.sampleRows.isEmpty()) return "id,feature_1,feature_2,target\n1,0.5,1.2,0\n"
        val headers = dataset.sampleRows[0].keys.toList()
        val headerLine = headers.joinToString(",")
        val rowLines = dataset.sampleRows.map { row ->
            headers.joinToString(",") { h ->
                val v = row[h] ?: ""
                if (v.contains(",") || v.contains("\"")) "\"${v.replace("\"", "\"\"")}\"" else v
            }
        }
        return (listOf(headerLine) + rowLines).joinToString("\n")
    }

    fun generateJson(dataset: Dataset): String {
        val rows = dataset.sampleRows.map { row ->
            val entries = row.map { (k, v) -> "\"$k\": \"$v\"" }.joinToString(", ")
            "  { $entries }"
        }.joinToString(",\n")
        return "[\n$rows\n]"
    }
